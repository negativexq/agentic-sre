"""Calibration measurement harness (M19-7.C): one candidate, one raw measurement.

The caller names a single candidate (a resource limit, optionally a request
and a memory ballast) for one workload container. On a fresh dedicated product
cluster the harness applies it with the existing ``SetResources`` action (and
verifies it), sets the ballast through the workload's existing fault endpoint,
turns on the Service-DNS traffic driver, waits a settle period and measures a
configured window with the product's own read-only resource-pressure reader —
the exact query and peak the A2 rule would see. It records the raw result.

It does not search candidates, tune, find passing values, read scenario
expectations, change limits from results or correct values: the observed peak
is recorded as Prometheus reports it (the scrape topology is recorded next to
it). Calibration decisions (M19-7.1–7.4) are made by the owner on these records.
"""

from __future__ import annotations

import json
import subprocess
from collections.abc import Callable, Mapping
from dataclasses import asdict, dataclass
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any, Literal
from urllib.parse import urlencode

from sqlalchemy import create_engine
from sqlalchemy.pool import StaticPool

from packages.evals.product.actions import SetResources
from packages.evals.product.live import (
    NAMESPACE,
    TRAFFIC_RATE,
    TRAFFIC_SEED,
    TRAFFIC_TARGET,
    LiveBackend,
    baseline_faults,
)
from packages.evals.product.runner import RunnerConfig, await_evidence
from packages.rca.investigation.prometheus import _resource_cpu_query, _resource_memory_query
from packages.rca.model import EntityRef, InvestigationQuery, ProviderReadFailure, ResourcePressure
from packages.rca.provider_adapter import ProviderAdapter, ProviderReaders
from packages.storage.database import create_session_factory
from packages.storage.models import Base

Resource = Literal["cpu", "memory"]
UNDERLYING = {
    "cpu": ("container_cpu_cfs_throttled_periods_total", "container_cpu_cfs_periods_total"),
    "memory": ("container_memory_working_set_bytes", "kube_pod_container_resource_limits"),
}


@dataclass(frozen=True, slots=True)
class Candidate:
    """One exact condition to measure; never generated by the harness."""

    resource: Resource
    service: str = "order-service"
    container: str = "order-service"
    limit: str | None = None
    request: str | None = None
    ballast_mb: int | None = None

    def __post_init__(self) -> None:
        if self.resource not in ("cpu", "memory"):
            raise ValueError("resource is cpu or memory")
        if self.limit is None and self.ballast_mb is None:
            raise ValueError("a candidate sets a limit, a ballast, or both")
        if self.request is not None and self.limit is None:
            raise ValueError("a request is only set together with a limit")
        if self.ballast_mb is not None and self.ballast_mb < 0:
            raise ValueError("ballast_mb must be non-negative")

    @property
    def label(self) -> str:
        parts = [self.resource, self.service, f"limit-{self.limit or 'default'}"]
        if self.request:
            parts.append(f"request-{self.request}")
        if self.ballast_mb is not None:
            parts.append(f"ballast-{self.ballast_mb}mb")
        return "_".join(parts)


@dataclass(frozen=True, slots=True)
class Window:
    settle: timedelta = timedelta(minutes=2)
    measure: timedelta = timedelta(minutes=10)

    def __post_init__(self) -> None:
        if self.settle < timedelta(0) or not timedelta(0) < self.measure <= timedelta(hours=1):
            raise ValueError("settle >= 0 and 0 < measure <= 1 h (the reader's bound)")


Reader = Callable[[EntityRef, datetime, datetime], tuple[ResourcePressure, ...]]
HostStats = Callable[[], Any]


def product_reader(base_url: str) -> Reader:
    """The product's A2 resource-pressure read, through the provider boundary.

    The ``ProviderAdapter`` records its tape into a throwaway in-memory database
    owned by this measurement: nothing reaches the product's storage.
    """
    engine = create_engine(
        "sqlite://", poolclass=StaticPool, connect_args={"check_same_thread": False}
    )
    Base.metadata.create_all(engine)
    adapter = ProviderAdapter(
        run_id="calibration",
        caller_class="CAPTURE",
        session_factory=create_session_factory(engine),
        readers=ProviderReaders.from_urls(prometheus_url=base_url),
    )

    def read(pod: EntityRef, start: datetime, end: datetime) -> tuple[ResourcePressure, ...]:
        result = adapter.query_resource_pressure(pod, InvestigationQuery(start=start, end=end))
        if isinstance(result, ProviderReadFailure):
            raise RuntimeError(f"Prometheus read failed: {result}")
        return tuple(result)

    return read


def docker_stats() -> Any:
    """Host contention at this moment: every running container's CPU/memory, raw."""
    output = subprocess.run(  # noqa: S603 - fixed argv
        ["docker", "stats", "--no-stream", "--format", "{{json .}}"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return [json.loads(line) for line in output.splitlines() if line.strip()]


def _get(http: Callable[..., Any], url: str) -> Any:
    try:
        return http("GET", url, {})
    except Exception as error:  # recorded, never fatal: the peak is what is measured
        return {"error": f"{type(error).__name__}: {error}"}


def measure(
    backend: LiveBackend,
    candidate: Candidate,
    window: Window,
    *,
    prometheus_url: str,
    reader: Reader,
    host_stats: HostStats = docker_stats,
    provenance: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Run one candidate on a fresh cluster and return the raw measurement record."""
    backend.cluster_up()
    traffic = False
    try:
        backend.deploy_observability_and_workload()
        backend.wait_workload_ready()
        backend.start_fresh_db_and_control_plane()
        control, evidence = backend.control(), backend.evidence()
        applied: dict[str, Any] = {}
        if candidate.limit is not None:
            action = SetResources(
                candidate.service,
                limits={candidate.resource: candidate.limit},
                requests={candidate.resource: candidate.request} if candidate.request else {},
                container=candidate.container,
            )
            receipt = action.apply(control)
            await_evidence(action, receipt, evidence, control, RunnerConfig())
            action.verify(evidence, receipt)
            applied["set_resources"] = {"verified": True, "at": receipt.started_at.isoformat()}
        if candidate.ballast_mb is not None:
            control.post(
                f"{control.service_urls[candidate.service]}/__faults",
                {**baseline_faults(candidate.service), "memory_ballast_mb": candidate.ballast_mb},
            )
            applied["ballast"] = {"memory_ballast_mb": candidate.ballast_mb}
        backend.set_traffic(True)
        traffic = True
        control.wait(window.settle)
        start, host_before = control.now(), host_stats()
        control.wait(window.measure)
        end, host_after = control.now(), host_stats()
        pod = control.pod_of(candidate.service)
        target = EntityRef(kind="Pod", name=pod.name, namespace=NAMESPACE)
        records = [
            item
            for item in reader(target, start, end)
            if item.container == candidate.container and item.resource == candidate.resource
        ]
        query = (
            _resource_cpu_query(target)
            if candidate.resource == "cpu"
            else _resource_memory_query(target)
        )
        series = {
            name: _get(
                backend.http,
                f"{prometheus_url}/api/v1/series?"
                + urlencode(
                    {
                        "match[]": f'{name}{{namespace="{NAMESPACE}",pod="{pod.name}"}}',
                        "start": start.timestamp(),
                        "end": end.timestamp(),
                    }
                ),
            )
            for name in UNDERLYING[candidate.resource]
        }
        targets = _get(backend.http, f"{prometheus_url}/api/v1/targets?state=active")
        return {
            "schema": "agentic-sre.calibration-measurement.v1",
            "candidate": asdict(candidate),
            "metric": f"{candidate.resource} pressure (product A2 reader)",
            "query": query,
            "window_start": start.isoformat(),
            "window_end": end.isoformat(),
            "settle_seconds": window.settle.total_seconds(),
            "applied": applied,
            "pod": {"name": pod.name, "uid": pod.uid},
            "traffic": {
                "target": TRAFFIC_TARGET,
                "rate_per_second": TRAFFIC_RATE,
                "seed": TRAFFIC_SEED,
                "concurrency": 1,
            },
            "raw": [item.model_dump(mode="json") for item in records],
            "raw_peak": max((item.peak for item in records), default=None),
            "scrape": {"series": series, "targets": targets},
            "host": {"before": host_before, "after": host_after},
            "provenance": dict(provenance or {}),
        }
    finally:
        if traffic:
            try:
                backend.set_traffic(False)
            except Exception:  # teardown below removes it anyway
                pass
        backend.cluster_down()


def write_record(root: Path, run: str, record: Mapping[str, Any]) -> Path:
    """Create-only record at ``.local/product-bench/calibration/<run>/<label>.json``."""
    label = Candidate(**record["candidate"]).label
    path = root.joinpath("calibration", run, f"{label}.json")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8") as handle:
        json.dump(record, handle, indent=2, sort_keys=True, default=str)
        handle.write("\n")
    return path


